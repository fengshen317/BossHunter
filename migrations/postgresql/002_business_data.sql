CREATE TABLE IF NOT EXISTS jobs (
    id TEXT PRIMARY KEY, title TEXT NOT NULL, company TEXT NOT NULL, salary TEXT, city TEXT,
    experience TEXT, jd TEXT, hr_name TEXT, hr_title TEXT, hr_active TEXT, company_size TEXT,
    company_industry TEXT, district TEXT, company_background TEXT, registered_capital TEXT, url TEXT,
    score INTEGER DEFAULT 0, quick_score INTEGER DEFAULT 0, score_reason TEXT, greeting TEXT,
    resume_path TEXT, conversation_id TEXT, status TEXT DEFAULT 'pending', error_retry_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES jobs(id), action TEXT NOT NULL, detail TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS risk_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL, detail TEXT, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workbench_tasks (
    id TEXT PRIMARY KEY, mode TEXT NOT NULL, label TEXT NOT NULL, status TEXT NOT NULL,
    logs TEXT NOT NULL DEFAULT '[]', error TEXT, created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
    deadline_at TEXT, stop_reason TEXT, stage TEXT
);

CREATE TABLE IF NOT EXISTS assistant_conversations (
    id TEXT PRIMARY KEY, title TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistant_messages (
    id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL, content TEXT NOT NULL, message_type TEXT NOT NULL DEFAULT 'text',
    metadata_json TEXT NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistant_memories (
    id TEXT PRIMARY KEY, user_id TEXT NOT NULL, memory_type TEXT NOT NULL, memory_key TEXT,
    category TEXT NOT NULL DEFAULT 'profile', content TEXT NOT NULL, value_json TEXT NOT NULL DEFAULT '{}',
    source_type TEXT NOT NULL DEFAULT 'explicit', source_conversation_id TEXT, source_message_id TEXT,
    source_excerpt TEXT NOT NULL DEFAULT '', supersedes_id TEXT, metadata_json TEXT NOT NULL DEFAULT '{}',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    status TEXT NOT NULL DEFAULT 'active', created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistant_conversation_contexts (
    conversation_id TEXT PRIMARY KEY REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    summary_text TEXT NOT NULL DEFAULT '', summary_token_count INTEGER NOT NULL DEFAULT 0,
    summarized_through_message_id TEXT, pending_digest_json TEXT NOT NULL DEFAULT '[]',
    pending_intent_json TEXT NOT NULL DEFAULT '{}', active_goal_json TEXT NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistant_bad_cases (
    id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    assistant_message_id TEXT NOT NULL UNIQUE REFERENCES assistant_messages(id) ON DELETE CASCADE,
    user_message_id TEXT, category TEXT NOT NULL, expected_intent TEXT NOT NULL DEFAULT '',
    feedback TEXT NOT NULL DEFAULT '', user_message TEXT NOT NULL DEFAULT '', assistant_answer TEXT NOT NULL,
    intent_json TEXT NOT NULL DEFAULT '{}', routing_json TEXT NOT NULL DEFAULT '{}', status TEXT NOT NULL DEFAULT 'open',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS assistant_message_ratings (
    assistant_message_id TEXT PRIMARY KEY REFERENCES assistant_messages(id) ON DELETE CASCADE,
    conversation_id TEXT NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    rating TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
CREATE INDEX IF NOT EXISTS idx_jobs_score ON jobs(score);
CREATE INDEX IF NOT EXISTS idx_history_job_id ON history(job_id);
CREATE INDEX IF NOT EXISTS idx_risk_events_type ON risk_events(event_type);
CREATE INDEX IF NOT EXISTS idx_workbench_tasks_updated_at ON workbench_tasks(updated_at);
CREATE INDEX IF NOT EXISTS idx_assistant_messages_conversation
	ON assistant_messages(conversation_id, created_at, id);
CREATE INDEX IF NOT EXISTS idx_assistant_memories_user ON assistant_memories(user_id, status, updated_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_assistant_memories_active_key
	ON assistant_memories(user_id, memory_key) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_assistant_bad_cases_status ON assistant_bad_cases(status, created_at);
