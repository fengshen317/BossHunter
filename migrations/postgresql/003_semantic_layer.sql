-- BossHunter 问数语义层：结构化流程事件及只读分析视图。
CREATE TABLE IF NOT EXISTS job_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    event_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source TEXT NOT NULL DEFAULT 'application',
    from_status TEXT,
    to_status TEXT,
    attributes_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_job_events_job_time ON job_events(job_id, event_time);
CREATE INDEX IF NOT EXISTS idx_job_events_type_time ON job_events(event_type, event_time);

CREATE OR REPLACE FUNCTION record_job_status_event() RETURNS trigger AS $$
DECLARE
    mapped_event TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO job_events (job_id, event_type, event_time, source, to_status)
        VALUES (NEW.id, 'job_collected', NEW.created_at, 'database_trigger', NEW.status);
        RETURN NEW;
    END IF;
    IF OLD.status IS NOT DISTINCT FROM NEW.status THEN
        RETURN NEW;
    END IF;
    mapped_event := CASE NEW.status
        WHEN 'filtered' THEN 'prefilter_rejected'
        WHEN 'scored' THEN 'ai_scored'
        WHEN 'ready' THEN 'greeting_generated'
        WHEN 'approved' THEN 'user_approved'
        WHEN 'rejected' THEN 'user_rejected'
        WHEN 'sent' THEN 'greeting_sent'
        WHEN 'replied' THEN 'hr_replied'
        WHEN 'needs_resume' THEN 'resume_requested'
        WHEN 'resume_sent' THEN 'resume_sent'
        WHEN 'follow_up_sent' THEN 'follow_up_sent'
        WHEN 'error' THEN 'send_failed'
        ELSE 'status_changed'
    END;
    INSERT INTO job_events (job_id, event_type, source, from_status, to_status)
    VALUES (NEW.id, mapped_event, 'database_trigger', OLD.status, NEW.status);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_jobs_semantic_event ON jobs;
CREATE TRIGGER trg_jobs_semantic_event
AFTER INSERT OR UPDATE OF status ON jobs
FOR EACH ROW EXECUTE FUNCTION record_job_status_event();

CREATE OR REPLACE VIEW semantic_job_current AS
SELECT id AS job_id, title, company, city, district, experience, company_size,
    company_industry, score AS ai_score, quick_score, status AS current_status,
    title <> 'HR主动沟通' AND BTRIM(COALESCE(title, '')) <> ''
        AND BTRIM(COALESCE(jd, '')) <> '' AS is_formal_job,
    created_at AS collected_at, updated_at
FROM jobs;

CREATE OR REPLACE VIEW semantic_job_funnel AS
SELECT j.id AS job_id, j.created_at AS collected_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'ai_scored') AS scored_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'user_approved') AS approved_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'greeting_sent') AS sent_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'hr_replied') AS first_replied_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'resume_requested') AS resume_requested_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'resume_sent') AS resume_sent_at,
    MIN(e.event_time) FILTER (WHERE e.event_type = 'follow_up_sent') AS follow_up_at
FROM jobs j
LEFT JOIN job_events e ON e.job_id = j.id
GROUP BY j.id, j.created_at;

COMMENT ON TABLE job_events IS '岗位流程的结构化事件事实表，供问数漏斗和耗时指标使用';
COMMENT ON VIEW semantic_job_current IS '一岗一行的当前状态分析视图';
COMMENT ON VIEW semantic_job_funnel IS '一岗一行的阶段首次到达时间分析视图';
